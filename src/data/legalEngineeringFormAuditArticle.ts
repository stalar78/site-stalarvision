const linkedParagraph = (
  text: string,
  phrase: string,
  href: string,
): ArticleTextSegment[] => {
  const phraseIndex = text.indexOf(phrase);

  if (phraseIndex === -1) {
    return [{ text }];
  }

  return [
    { text: text.slice(0, phraseIndex) },
    { text: phrase, href },
    { text: text.slice(phraseIndex + phrase.length) },
  ].filter((segment) => segment.text);
};

